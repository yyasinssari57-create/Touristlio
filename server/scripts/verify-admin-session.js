function mergeCookies(jar, setCookie) {
  if (!setCookie) return [];
  const arr = Array.isArray(setCookie) ? setCookie : [setCookie];
  for (const line of arr) {
    const part = line.split(';')[0];
    const eq = part.indexOf('=');
    if (eq < 1) continue;
    jar[part.slice(0, eq).trim()] = part.slice(eq + 1);
  }
  return arr;
}
function cookieHeader(jar) {
  return Object.entries(jar).map(([k, v]) => `${k}=${v}`).join('; ');
}

async function jsonRequest(url, { method = 'GET', body, headers, jar } = {}) {
  const hdrs = { ...(headers || {}) };
  if (jar && Object.keys(jar).length) hdrs.Cookie = cookieHeader(jar);
  const payload = body == null ? null : (typeof body === 'string' ? body : JSON.stringify(body));
  if (payload != null && !hdrs['Content-Type']) hdrs['Content-Type'] = 'application/json';
  const res = await fetch(url, { method, headers: hdrs, body: payload });
  const rawSetCookie = res.headers.getSetCookie ? res.headers.getSetCookie() : [];
  if (jar) mergeCookies(jar, rawSetCookie);
  const text = await res.text();
  let json = {};
  try { json = JSON.parse(text); } catch { /* ignore */ }
  return { status: res.status, json, text, setCookie: rawSetCookie };
}

async function formRequest(url, { jar, headers, fieldName, filename, buffer }) {
  const hdrs = { ...(headers || {}) };
  if (jar && Object.keys(jar).length) hdrs.Cookie = cookieHeader(jar);
  const fd = new FormData();
  fd.append(fieldName, new Blob([buffer], { type: 'image/jpeg' }), filename);
  const res = await fetch(url, { method: 'POST', headers: hdrs, body: fd });
  const rawSetCookie = res.headers.getSetCookie ? res.headers.getSetCookie() : [];
  if (jar) mergeCookies(jar, rawSetCookie);
  const text = await res.text();
  let json = {};
  try { json = JSON.parse(text); } catch { /* ignore */ }
  return { status: res.status, json, text, setCookie: rawSetCookie };
}

function waitForServer(url, tries = 400) {
  return new Promise((resolve, reject) => {
    let n = 0;
    const tick = () => {
      n += 1;
      const req = http.get(url, { timeout: 1000 }, (res) => { res.resume(); resolve(); });
      req.on('error', () => { if (n >= tries) reject(new Error('server did not start')); else setTimeout(tick, 250); });
      req.on('timeout', () => { req.destroy(); if (n >= tries) reject(new Error('server did not start')); else setTimeout(tick, 250); });
    };
    tick();
  });
}

async function makeTestJpeg() {
  const sharp = require('sharp');
  return sharp({ create: { width: 48, height: 48, channels: 3, background: { r: 60, g: 120, b: 200 } } })
    .jpeg({ quality: 80 })
    .toBuffer();
}

function decodeJwtPayload(token) {
  const part = String(token || '').split('.')[1];
  if (!part) return null;
  try {
    return JSON.parse(Buffer.from(part, 'base64').toString('utf8'));
  } catch {
    return null;
  }
}

function cookieMaxAgeSeconds(setCookieLines, name) {
  const line = (setCookieLines || []).find((l) => l.startsWith(`${name}=`));
  if (!line) return null;
  const m = /Max-Age=(\d+)/i.exec(line);
  return m ? Number(m[1]) : null;
}

async function checkLive(base) {
  const root = base.replace(/\/$/, '');
  const jar = {};
  const adminEmail = process.env.ADMIN_EMAIL || 'admin@test.local';
  const adminPassword = process.env.ADMIN_PASSWORD || 'TestAdmin123!';

  const login = await jsonRequest(`${root}/api/auth/login`, {
    method: 'POST', jar, headers: { Origin: root }, body: { email: adminEmail, password: adminPassword },
  });
  if (login.status !== 200) { fail(`admin login HTTP ${login.status}: ${login.text.slice(0, 180)}`); return; }
  ok('admin girişi yapıldı (taze oturum)');

  // (a) fresh login → ~30 günlük token + çerez
  const tokenMaxAge = cookieMaxAgeSeconds(login.setCookie, 'tl_token');
  const THIRTY_DAYS_S = 30 * 24 * 60 * 60;
  if (tokenMaxAge == null) {
    fail('giriş yanıtında tl_token Set-Cookie Max-Age bulunamadı');
  } else if (Math.abs(tokenMaxAge - THIRTY_DAYS_S) > 60) {
    fail(`tl_token çerez Max-Age beklenenden farklı: ${tokenMaxAge}s (beklenen ~${THIRTY_DAYS_S}s / 30 gün)`);
  } else ok(`tl_token çerez Max-Age = ${tokenMaxAge}s (~30 gün)`);

  const payload = decodeJwtPayload(jar.tl_token);
  if (!payload || !payload.exp || !payload.iat) {
    fail('tl_token JWT payload çözülemedi veya exp/iat eksik');
  } else {
    const lifetimeS = payload.exp - payload.iat;
    if (Math.abs(lifetimeS - THIRTY_DAYS_S) > 60) {
      fail(`JWT exp-iat beklenenden farklı: ${lifetimeS}s (beklenen ~${THIRTY_DAYS_S}s / 30 gün)`);
    } else ok(`JWT exp-iat = ${lifetimeS}s (~30 gün) — çerez Max-Age ile hizalı`);
  }

  // (b) süresi dolmuş token → admin yükleme ucunda net 401 + sessionExpired
  const secret = process.env.JWT_SECRET || 'dev-secret-change-me';
  const expiredToken = jwt.sign(
    { id: payload?.id, email: adminEmail, role: 'admin', name: 'Test Admin' },
    secret,
    { expiresIn: -1 },
  );
  const imgBuf = await makeTestJpeg();
  const expiredJar = { tl_token: expiredToken };
  const expiredUpload = await formRequest(`${root}/api/admin/media`, {
    jar: expiredJar, headers: { Origin: root }, fieldName: 'image', filename: 'expired.jpg', buffer: imgBuf,
  });
  if (expiredUpload.status !== 401 || expiredUpload.json?.sessionExpired !== true) {
    fail(`süresi dolmuş token ile POST /api/admin/media beklenen 401 sessionExpired değil: ${expiredUpload.status} ${expiredUpload.text.slice(0, 200)}`);
  } else {
    ok(`süresi dolmuş token ile yükleme → 401, net mesaj: "${expiredUpload.json.error}"`);
  }
  const expiredSetCookie = (expiredUpload.setCookie || []).find((l) => l.startsWith('tl_token='));
  if (!expiredSetCookie || !/Max-Age=0|tl_token=;/i.test(expiredSetCookie)) {
    fail('süresi dolmuş token ile istek sonrası tl_token çerezi temizlenmedi (Yasin tekrar giriş ekranını net görmeyebilir)');
  } else ok('süresi dolmuş token ile istek sonrası sunucu tl_token çerezini temizliyor (tekrar giriş akışı tetiklenir)');

  // Geçersiz (bozuk) token da aynı şekilde net 401 vermeli — sessiz başarısızlık yok.
  const garbageJar = { tl_token: 'not-a-real-jwt' };
  const garbageUpload = await formRequest(`${root}/api/admin/media`, {
    jar: garbageJar, headers: { Origin: root }, fieldName: 'image', filename: 'bad.jpg', buffer: imgBuf,
  });
  if (garbageUpload.status !== 401) {
    fail(`bozuk token ile POST /api/admin/media beklenen 401 değil: ${garbageUpload.status}`);
  } else ok('bozuk/geçersiz token ile yükleme → 401 (sessiz başarısızlık yok)');

  // (c) normal, süresi dolmamış oturumla uçtan uca yükleme hâlâ çalışıyor mu
  // (PR #67'nin 12 MB düzeltmesi bu düzeltmeyle birlikte hâlâ ayakta mı)
  const media = await formRequest(`${root}/api/admin/media`, {
    jar, headers: { Origin: root }, fieldName: 'image', filename: 'media.jpg', buffer: imgBuf,
  });
  if (media.status !== 200 || !media.json?.data?.url) {
    fail(`normal oturumla POST /api/admin/media HTTP ${media.status}: ${media.text.slice(0, 200)}`);
  } else ok(`normal oturumla POST /api/admin/media -> 200 (medya kütüphanesi / şehir-kategori görseli yolu)`);

  const hero = await formRequest(`${root}/api/admin/hero-image`, {
    jar, headers: { Origin: root }, fieldName: 'image', filename: 'hero.jpg', buffer: imgBuf,
  });
  if (hero.status !== 200 || !hero.json?.data?.url) {
    fail(`normal oturumla POST /api/admin/hero-image HTTP ${hero.status}: ${hero.text.slice(0, 200)}`);
  } else ok('normal oturumla POST /api/admin/hero-image -> 200');

  // Slugs are unique-constrained — suffix with a timestamp so reruns (and
  // leftover soft-deleted rows from earlier runs) never collide.
  const runSuffix = Date.now();
  const createCity = await jsonRequest(`${root}/api/admin/cities`, {
    method: 'POST', jar, headers: { Origin: root },
    body: { name: `Verify Session City ${runSuffix}`, country: 'TR', slug: `verify-session-city-${runSuffix}` },
  });
  const cityId = createCity.json?.data?.city?.id;
  if (createCity.status !== 201 || !cityId) {
    fail(`POST /api/admin/cities HTTP ${createCity.status}: ${createCity.text.slice(0, 200)}`);
  } else {
    const updateCity = await jsonRequest(`${root}/api/admin/cities/${cityId}`, {
      method: 'PUT', jar, headers: { Origin: root }, body: { imageUrl: media.json.data.url },
    });
    if (updateCity.status !== 200 || updateCity.json?.data?.city?.imageUrl !== media.json.data.url) {
      fail(`şehir kapak görseli (yüklenen medya URL'si) kaydedilemedi: HTTP ${updateCity.status}`);
    } else ok('yüklenen görsel şehir kapak görseli olarak kaydedildi (admin.html şehir düzenle akışıyla aynı yol)');
    await jsonRequest(`${root}/api/admin/cities/${cityId}`, { method: 'DELETE', jar, headers: { Origin: root } });
  }

  const createCategory = await jsonRequest(`${root}/api/admin/categories`, {
    method: 'POST', jar, headers: { Origin: root },
    body: { slug: `verify-session-cat-${runSuffix}`, nameTr: 'Doğrulama Kategorisi', nameEn: 'Verify Category' },
  });
  const categoryId = createCategory.json?.data?.category?.id;
  if (createCategory.status !== 201 || !categoryId) {
    fail(`POST /api/admin/categories HTTP ${createCategory.status}: ${createCategory.text.slice(0, 200)}`);
  } else {
    const updateCategory = await jsonRequest(`${root}/api/admin/categories/${categoryId}`, {
      method: 'PUT', jar, headers: { Origin: root }, body: { imageUrl: media.json.data.url },
    });
    if (updateCategory.status !== 200 || updateCategory.json?.data?.category?.imageUrl !== media.json.data.url) {
      fail(`kategori kapak görseli (yüklenen medya URL'si) kaydedilemedi: HTTP ${updateCategory.status}`);
    } else ok('yüklenen görsel kategori kapak görseli olarak kaydedildi (admin.html kategori düzenle akışıyla aynı yol)');
    await jsonRequest(`${root}/api/admin/categories/${categoryId}`, { method: 'DELETE', jar, headers: { Origin: root } });
  }

  const createPlace = await jsonRequest(`${root}/api/admin/places`, {
    method: 'POST', jar, headers: { Origin: root },
    body: { name: 'Verify Session Place', country: 'TR', city: 'Istanbul', category: 'tarihi', status: 'published' },
  });
  const placeId = createPlace.json?.data?.id;
  if (createPlace.status !== 201 || !placeId) {
    fail(`POST /api/admin/places HTTP ${createPlace.status}: ${createPlace.text.slice(0, 200)}`);
  } else {
    const photos = await formRequest(`${root}/api/admin/places/${placeId}/photos`, {
      jar, headers: { Origin: root }, fieldName: 'photos', filename: 'place.jpg', buffer: imgBuf,
    });
    if (photos.status !== 200 || !photos.json?.data?.photos?.length) {
      fail(`normal oturumla POST /api/admin/places/:id/photos HTTP ${photos.status}: ${photos.text.slice(0, 200)}`);
    } else ok('normal oturumla POST /api/admin/places/:id/photos -> 200 (PR #67 ile birlikte hâlâ çalışıyor)');
    await jsonRequest(`${root}/api/admin/places/${placeId}`, { method: 'DELETE', jar, headers: { Origin: root } });
  }
}

function spawnServer(port) {
  return spawn(process.execPath, [path.join(ROOT, 'server', 'index.js')], {
    cwd: ROOT,
    env: {
      ...process.env,
      PORT: String(port),
      NODE_ENV: 'development',
      SITEMAP_ON_START: 'false',
      LIVE_DATA_CRON: 'false',
      RECAPTCHA_SITE_KEY: '',
      RECAPTCHA_SECRET: '',
    },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

async function main() {
  const given = process.env.VERIFY_SESSION_URL;
  if (given) {
    await checkLive(given);
  } else {
    const port = process.env.VERIFY_SESSION_PORT || '3093';
    const child = spawnServer(port);
    let stderr = '';
    child.stderr.on('data', (c) => { stderr += c; });
    const base = `http://127.0.0.1:${port}`;
    try {
      await waitForServer(base, 400);
      await checkLive(base);
    } catch (e) {
      fail(`live server :${port}: ${e.message}${stderr ? ` (${stderr.slice(0, 300)})` : ''}`);
    } finally {
      child.kill('SIGTERM');
      await new Promise((r) => setTimeout(r, 200));
      try { child.kill('SIGKILL'); } catch { /* ignore */ }
    }
  }

  if (failed) {
    console.error(`verify-admin-session: ${failed} failed`);
    process.exit(1);
  }
  console.log('verify-admin-session: ok');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
