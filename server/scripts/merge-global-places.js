function buildRow(id, row) {
  const [name, location, country, city, district, category, aliases, isLocal, entryFee] = row;
  const gR = 4.2 + ((id * 7) % 8) / 10;
  const gC = `${12 + (id * 17) % 180},${(id * 13) % 900}`;
  return {
    id,
    name,
    location,
    country,
    city,
    district: district || city,
    category,
    googleRating: Math.round(gR * 10) / 10,
    googleCount: gC,
    imageUrl: CAT_IMG[category] || CAT_IMG.landmark,
    isLocal: !!isLocal,
    entryFee: entryFee || (isLocal ? 'Ücretsiz' : 'Ücretli'),
    bestTime: 'Sabah erken veya gün batımı',
    description: `${name}, ${city} — dünya çapında gezginlerin sık aradığı ${category} destinasyonu. Touristlio'da Tiola ile deneyim paylaşın.`,
    history: `${country} / ${city} bölgesinde kültürel ve doğal öneme sahip bir durak.`,
    tips: 'Kalabalık saatlerden kaçının. Yerel ipuçları için onaylı Tiola yorumlarına bakın.',
    tags: [country, city, category].filter(Boolean),
    searchAliases: aliases || [],
  };
}

const outPath = path.join(__dirname, '..', 'data', 'places.json');
const existing = JSON.parse(fs.readFileSync(outPath, 'utf8'));
const names = new Set(existing.map((p) => p.name.toLowerCase()));
let nextId = Math.max(...existing.map((p) => p.id), 0);

const merged = [...existing];
for (const row of EXTRA) {
  if (names.has(row[0].toLowerCase())) continue;
  nextId += 1;
  const place = buildRow(nextId, row);
  merged.push(place);
  names.add(row[0].toLowerCase());
}

// Ensure Istanbul aliases on existing Ayasofya etc.
const aliasPatches = {
  Ayasofya: ['Hagia Sophia', 'Aya Sofya', 'Istanbul', 'İstanbul'],
  'Galata Kulesi': ['Galata Tower', 'Istanbul', 'İstanbul'],
};
for (const p of merged) {
  if (aliasPatches[p.name]) {
    p.searchAliases = [...new Set([...(p.searchAliases || []), ...aliasPatches[p.name]])];
  }
  if (p.city === 'Istanbul' || p.city === 'İstanbul') {
    p.searchAliases = [...new Set([...(p.searchAliases || []), 'Istanbul', 'İstanbul', 'Constantinople'])];
  }
}

fs.writeFileSync(outPath, JSON.stringify(merged, null, 2), 'utf8');
